package com.example.ipixelclock.font

/**
 * The drawn font families.
 *
 * All original designs. The named inspirations — the Matrix's falling code, the
 * Star Wars titles, Star Trek's LCARS panels, an arcade cabinet's score counter —
 * are trademarked typefaces that cannot be redistributed in an APK. These are
 * drawn in that *style*, which is in any case the only way to get stems landing
 * on exact pixel boundaries at fourteen rows.
 *
 * Each family is authored at one main cut. `PixelFonts.Family.fit` scales it by
 * whole multiples for taller panels and falls back to a shorter family when a
 * panel is too short, so twelve cuts cover the whole iPixel type table.
 *
 * Digits are the work; a clock shows ten glyphs and a separator. Letters come
 * from SYSTEM where they are needed (the info row), which keeps the drawing here
 * honest instead of padded out with twenty-six shapes nothing renders.
 */
